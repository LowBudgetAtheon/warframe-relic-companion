#!/usr/bin/env node
/* Adds an encrypted secret to web/secrets.js.

   Usage:  SECRET_CODE="the code" node scripts/add-secret.mjs '<payload JSON>'

   The payload is encrypted with a key made from the code (PBKDF2-SHA256, then
   AES-GCM), so the public file reveals nothing until someone types the code into
   the app's "Enter code" box. The code itself is never written anywhere.
   Codes ignore capital letters and spaces.

   Payload types the app understands:
     {"type":"birthday","id":"bd-3","name":"…","month":1,"day":2,"message":"…","theme":"sd-b1"}
*/
import fs from "node:fs";
import { webcrypto as crypto } from "node:crypto";

const FILE = new URL("../web/secrets.js", import.meta.url);
const ITER = 600000;
const b64u = buf => Buffer.from(buf).toString("base64url");
const code = String(process.env.SECRET_CODE || "").toLowerCase().replace(/\s+/g, "");
if (!code) { console.error("Set SECRET_CODE"); process.exit(1); }
const payload = JSON.parse(process.argv[2] || "null");
if (!payload || !payload.id || !payload.type) { console.error("Pass a payload JSON with id and type"); process.exit(1); }

let cur = { salt: b64u(crypto.getRandomValues(new Uint8Array(16))), iter: ITER, list: [] };
if (fs.existsSync(FILE)) {
  const m = /window\.WRC_SECRETS = (\{[\s\S]*\});/.exec(fs.readFileSync(FILE, "utf8"));
  if (m) cur = JSON.parse(m[1]);
}
const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(code), "PBKDF2", false, ["deriveKey"]);
const key = await crypto.subtle.deriveKey({ name: "PBKDF2", hash: "SHA-256", salt: Buffer.from(cur.salt, "base64url"), iterations: cur.iter }, base, { name: "AES-GCM", length: 256 }, false, ["encrypt"]);
const iv = crypto.getRandomValues(new Uint8Array(12));
const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, new TextEncoder().encode(JSON.stringify(payload)));
cur.list.push({ i: b64u(iv), c: b64u(ct) });
fs.writeFileSync(FILE, `/* Encrypted secrets for the "Enter code" box. Generated by scripts/add-secret.mjs; do not edit by hand. */\nwindow.WRC_SECRETS = ${JSON.stringify(cur, null, 1)};\n`);
console.log(`Added secret ${cur.list.length}`);
